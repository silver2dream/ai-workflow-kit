package generate

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/silver2dream/ai-workflow-kit/internal/layout"
)

// A workflow an earlier awkit generated names the configuration at its
// earlier place in its first line. It is awkit's all the same. Were it taken
// for the project's own, an upgrade would leave it as it is for good, and the
// workflow would no longer follow the configuration.
func TestCIStateOf_AWorkflowOfAnEarlierAwkit(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) string {
		t.Helper()
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		return path
	}
	const earlierHeader = "# Generated by awkit from .ai/config/workflow.yaml. Do not edit: awkit keeps this file in step with the config.\n" +
		"# To change it by hand, delete this comment first; awkit then leaves the file alone.\n\n"

	tests := []struct {
		name, content string
		want          ciFileState
	}{
		{"as an earlier awkit wrote it", earlierHeader + "name: ci\n", ciOwnedByKit},
		{"as this awkit writes it", ciGeneratedHeader + "name: ci\n", ciOwnedByKit},
		{"taken over: the comment is gone", "name: ci\n", ciProjectOwn},
		{"taken over: the comment is not at the start", "name: ci\n" + ciGeneratedHeader, ciProjectOwn},
		{"a comment of the project's own", "# Generated by hand\nname: ci\n", ciProjectOwn},
	}
	for _, tt := range tests {
		if got := ciStateOf(write("ci.yml", tt.content)); got != tt.want {
			t.Errorf("%s: state %v, want %v", tt.name, got, tt.want)
		}
	}
	if got := ciStateOf(filepath.Join(dir, "none.yml")); got != ciMissing {
		t.Errorf("a file that is not there: state %v, want missing", got)
	}

	// What is written now names the configuration where it is now.
	if want := "# Generated by awkit from " + layout.ConfigFile + ". Do not edit:"; !strings.HasPrefix(ciGeneratedHeader, want) {
		t.Errorf("the header starts %q, want %q", ciGeneratedHeader[:60], want)
	}
}

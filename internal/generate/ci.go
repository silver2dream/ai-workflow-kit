// CIPolicy says what a generate run does about the CI workflows.
//
// awkit owns a workflow for as long as the file starts with ciGeneratedMark,
// and keeps the ones it owns in step with the config. A project takes a
// workflow over by deleting that line; after that only CIRewrite touches it.
type CIPolicy int

const (
	// CINone leaves every workflow alone.
	CINone CIPolicy = iota
	// CIRefresh rewrites the workflows awkit owns, removes the ones no repo
	// accounts for any more, and adds none.
	CIRefresh
	// CISync does what CIRefresh does and writes the workflows that are missing.
	CISync
	// CIRewrite writes every workflow, the ones the project took over included.
	CIRewrite
)

// ciGeneratedMark is how a workflow file starts while awkit owns it. The
// line goes on to name the configuration; an earlier awkit named it at its
// earlier place, and a workflow that starts so is awkit's all the same.
const ciGeneratedMark = "# Generated by awkit from "

const ciGeneratedHeader = ciGeneratedMark + layout.ConfigFile + ". Do not edit: awkit keeps this file in step with the config.\n" +
	"# To change it by hand, delete this comment first; awkit then leaves the file alone.\n\n"

// The actions a generated workflow uses. These majors all run on Node 24.
const (
	actionCheckout    = "actions/checkout@v7"
	actionSetupGo     = "actions/setup-go@v7"
	actionSetupDotnet = "actions/setup-dotnet@v6"
)

// ciDotnetSDK is the SDK a C# job installs: the one the godot-go skeleton
// targets. A project on another SDK takes its workflow over.
const ciDotnetSDK = "8.0.x"

// ciWorkflowFile is a workflow as the config says it should be.
type ciWorkflowFile struct {
	path    string
	content string
	subject string // what it is for, as a message names it
}

// ciPlan is what a run does to the workflow files.
type ciPlan struct {
	write  []ciWorkflowFile
	remove []string
	notes  []string
}

type ciFileState int

const (
	ciMissing    ciFileState = iota
	ciOwnedByKit             // generated, and not taken over
	ciProjectOwn             // written or taken over by the project
)

func ciStateOf(file string) ciFileState {
	data, err := os.ReadFile(file)
	switch {
	case err != nil:
		return ciMissing
	case strings.HasPrefix(string(data), ciGeneratedMark):
		return ciOwnedByKit
	default:
		return ciProjectOwn
	}
}

// planCIWorkflows decides what a run does: one workflow per repo that has a
// build or a test command (a repo with neither has nothing to run), plus the
// submodule check of a monorepo that has submodules.
//
// A workflow the project owns is left alone unless the policy is CIRewrite.
// And where the project owns .github/workflows/ci.yml, no per-repo workflow is
// added next to it: that is the one file earlier versions of the kit wrote
// for every repo at once, and the repos would be built twice.
func planCIWorkflows(stateRoot string, ctx *TemplateContext, policy CIPolicy) ciPlan {
	var plan ciPlan
	if policy == CINone {
		return plan
	}
	workflowDir := filepath.Join(stateRoot, ".github", "workflows")
	projectWorkflow := filepath.Join(workflowDir, "ci.yml")
	projectOwnsCI := ciStateOf(projectWorkflow) == ciProjectOwn
	// A note names a file as the generator's other lines do: from the
	// project's root.
	shown := progress{root: stateRoot}.path

	wanted := map[string]bool{}
	covered := false
	consider := func(file ciWorkflowFile, besideProjectCI bool) {
		wanted[file.path] = true
		state := ciStateOf(file.path)
		switch {
		case policy == CIRewrite, state == ciOwnedByKit:
			plan.write = append(plan.write, file)
		case state == ciProjectOwn:
			plan.notes = append(plan.notes, fmt.Sprintf("Kept: %s is the project's own", shown(file.path)))
		case besideProjectCI && projectOwnsCI:
			covered = true
		case policy == CIRefresh:
			plan.notes = append(plan.notes, fmt.Sprintf("No CI workflow for %s yet: awkit generate writes one", file.subject))
		default:
			plan.write = append(plan.write, file)
		}
	}

	for _, repo := range ctx.Repos {
		if strings.TrimSpace(repo.Verify.Build) == "" && strings.TrimSpace(repo.Verify.Test) == "" {
			plan.notes = append(plan.notes, fmt.Sprintf("No CI workflow for %s: its build and test commands are not set", repo.Name))
			continue
		}
		file := ciWorkflowFile{
			path:    ciWorkflowPath(stateRoot, repo),
			content: generateCIContent(repo, ctx.Git),
			subject: repo.Name,
		}
		consider(file, repo.Type != "submodule" && file.path != projectWorkflow)
	}

	// A monorepo with submodules also checks that every submodule commit is on
	// an allowed branch.
	if ctx.Project.Type == "monorepo" && ctx.HasSubmodules {
		consider(ciWorkflowFile{
			path:    filepath.Join(workflowDir, "validate-submodules.yml"),
			content: generateValidateSubmodulesWorkflow(ctx.Git),
			subject: "the submodule check",
		}, false)
	}

	if covered {
		plan.notes = append(plan.notes, fmt.Sprintf("Kept: %s is the project's own and is taken to cover every repo, so no per-repo workflow is added (awkit generate --generate-ci writes them)", shown(projectWorkflow)))
	}
	if policy == CIRewrite && projectOwnsCI && !wanted[projectWorkflow] && len(plan.write) > 0 {
		plan.notes = append(plan.notes, fmt.Sprintf("NOTE: %s does not come from this config; remove it if it repeats the per-repo workflows", shown(projectWorkflow)))
	}

	// A workflow awkit owns that no repo accounts for any more: the repo is
	// gone from the config, or lost its commands.
	entries, _ := os.ReadDir(workflowDir)
	for _, entry := range entries {
		file := filepath.Join(workflowDir, entry.Name())
		if !entry.IsDir() && !wanted[file] && ciStateOf(file) == ciOwnedByKit {
			plan.remove = append(plan.remove, file)
		}
	}

	return plan
}

// generateCIWorkflows carries out the plan and returns the files it wrote and
// the files it removed.
func generateCIWorkflows(stateRoot string, ctx *TemplateContext, policy CIPolicy, say progress) (written, removed []string, err error) {
	plan := planCIWorkflows(stateRoot, ctx, policy)
	for _, note := range plan.notes {
		say.say("%s", note)
	}
	for _, file := range plan.write {
		if err := os.MkdirAll(filepath.Dir(file.path), 0o755); err != nil {
			return written, removed, fmt.Errorf("CI workflow for %s: %w", file.subject, err)
		}
		if err := os.WriteFile(file.path, []byte(file.content), 0o644); err != nil {
			return written, removed, fmt.Errorf("CI workflow for %s: %w", file.subject, err)
		}
		written = append(written, file.path)
		say.say("wrote %s", say.path(file.path))
	}
	for _, file := range plan.remove {
		if err := os.Remove(file); err != nil {
			return written, removed, fmt.Errorf("remove stale CI workflow: %w", err)
		}
		removed = append(removed, file)
		say.say("removed %s (no repo in the configuration runs it any more)", say.path(file))
	}
	return written, removed, nil
}

// ciWorkflowPath is where a repo's workflow goes. A submodule is its own
// repository and carries its own workflow; the others live in the project's
// .github/workflows, one file per directory repo.
func ciWorkflowPath(stateRoot string, repo RepoConfig) string {
	switch repo.Type {
	case "submodule":
		return filepath.Join(stateRoot, filepath.FromSlash(ciRepoDir(repo.Path)), ".github", "workflows", "ci.yml")
	case "directory":
		return filepath.Join(stateRoot, ".github", "workflows", fmt.Sprintf("ci-%s.yml", repo.Name))
	default:
		return filepath.Join(stateRoot, ".github", "workflows", "ci.yml")
	}
}

// ciRepoDir is a repo path as a workflow names it: forward slashes, no
// trailing slash, "" for the repository root. The case is kept: the workflow
// runs on Linux whatever machine generated it.
func ciRepoDir(repoPath string) string {
	dir := path.Clean(strings.ReplaceAll(strings.TrimSpace(repoPath), "\\", "/"))
	if dir == "." || dir == "/" {
		return ""
	}
	return dir
}

// generateCIContent is the workflow of one repo: check out, set up the
// toolchain of the repo's language, then run the repo's own commands.
func generateCIContent(repo RepoConfig, git GitConfig) string {
	// A directory repo runs in its directory. A root repo is the checkout
	// itself, and a submodule's workflow lives in the submodule's repository.
	dir := ""
	if repo.Type == "directory" {
		dir = ciRepoDir(repo.Path)
	}

	var sb strings.Builder
	sb.WriteString(ciGeneratedHeader)
	fmt.Fprintf(&sb, "name: %s\n\n", strconv.Quote(repo.Name+" CI"))
	sb.WriteString("on:\n")
	sb.WriteString("  push:\n")
	fmt.Fprintf(&sb, "    branches: %s\n", ciBranches(git.IntegrationBranch, git.ReleaseBranch))
	sb.WriteString("  pull_request:\n")
	fmt.Fprintf(&sb, "    branches: %s\n\n", ciBranches(git.IntegrationBranch))
	sb.WriteString("permissions:\n")
	sb.WriteString("  contents: read\n\n")
	sb.WriteString("jobs:\n")
	sb.WriteString("  build:\n")
	sb.WriteString("    runs-on: ubuntu-latest\n")
	if dir != "" {
		sb.WriteString("    defaults:\n")
		sb.WriteString("      run:\n")
		fmt.Fprintf(&sb, "        working-directory: %s\n", strconv.Quote(dir))
	}
	sb.WriteString("    steps:\n")
	fmt.Fprintf(&sb, "      - uses: %s\n", actionCheckout)

	// A toolchain the job has no setup step for (and a language the kit does
	// not know) gets a job that only runs the repo's own commands.
	switch awkrepo.ToolchainOf(repo.Language) {
	case awkrepo.ToolchainGo:
		// The Go version is the module's own. The cache key takes go.mod as
		// well, because a module without dependencies has no go.sum.
		fmt.Fprintf(&sb, "      - uses: %s\n", actionSetupGo)
		sb.WriteString("        with:\n")
		fmt.Fprintf(&sb, "          go-version-file: %s\n", strconv.Quote(path.Join(dir, "go.mod")))
		sb.WriteString("          cache-dependency-path: |\n")
		fmt.Fprintf(&sb, "            %s\n", path.Join(dir, "go.mod"))
		fmt.Fprintf(&sb, "            %s\n", path.Join(dir, "go.sum"))
	case awkrepo.ToolchainDotnet:
		fmt.Fprintf(&sb, "      - uses: %s\n", actionSetupDotnet)
		sb.WriteString("        with:\n")
		fmt.Fprintf(&sb, "          dotnet-version: %s\n", strconv.Quote(ciDotnetSDK))
	}

	for _, step := range []struct{ name, command string }{
		{"Setup", repo.Verify.Setup},
		{"Build", repo.Verify.Build},
		{"Test", repo.Verify.Test},
	} {
		writeRunStep(&sb, step.name, step.command)
	}

	return sb.String()
}

// writeRunStep adds a step that runs a command, or nothing when the command
// is empty. The command goes into a block scalar, so whatever it contains
// (quotes, a colon, a #, several lines) reaches the shell unchanged.
func writeRunStep(sb *strings.Builder, name, command string) {
	command = strings.TrimSpace(strings.ReplaceAll(command, "\r\n", "\n"))
	if command == "" {
		return
	}
	fmt.Fprintf(sb, "      - name: %s\n", name)
	sb.WriteString("        run: |\n")
	for _, line := range strings.Split(command, "\n") {
		if strings.TrimSpace(line) == "" {
			sb.WriteString("\n")
			continue
		}
		sb.WriteString("          " + line + "\n")
	}
}

// ciBranches renders the branch filter of a trigger: every name once, in the
// order given, empty ones left out.
func ciBranches(names ...string) string {
	var quoted []string
	seen := map[string]bool{}
	for _, name := range names {
		name = strings.TrimSpace(name)
		if name == "" || seen[name] {
			continue
		}
		seen[name] = true
		quoted = append(quoted, strconv.Quote(name))
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

func generateValidateSubmodulesWorkflow(git GitConfig) string {
	var sb strings.Builder

	sb.WriteString(ciGeneratedHeader)
	sb.WriteString("name: validate-submodules\n\n")
	sb.WriteString("on:\n")
	sb.WriteString("  pull_request:\n")
	if git.IntegrationBranch != git.ReleaseBranch && git.ReleaseBranch != "" {
		sb.WriteString(fmt.Sprintf("    branches: [\"%s\", \"%s\"]\n", git.IntegrationBranch, git.ReleaseBranch))
	} else {
		sb.WriteString(fmt.Sprintf("    branches: [\"%s\"]\n", git.IntegrationBranch))
	}
	sb.WriteString("  push:\n")
	sb.WriteString(fmt.Sprintf("    branches: [\"%s\"]\n\n", git.IntegrationBranch))

	sb.WriteString("jobs:\n")
	sb.WriteString("  validate:\n")
	sb.WriteString("    runs-on: ubuntu-latest\n")
	sb.WriteString("    steps:\n")
	sb.WriteString("      - name: Checkout (with submodules)\n")
	sb.WriteString(fmt.Sprintf("        uses: %s\n", actionCheckout))
	sb.WriteString("        with:\n")
	sb.WriteString("          submodules: recursive\n")
	sb.WriteString("          fetch-depth: 0\n")
	sb.WriteString("          token: ${{ secrets.SUBMODULES_TOKEN }}\n\n")

	sb.WriteString("      - name: Ensure submodules initialised\n")
	sb.WriteString("        run: |\n")
	sb.WriteString("          git submodule update --init --recursive\n")
	sb.WriteString("          git submodule status --recursive\n\n")

	sb.WriteString("      - name: Verify submodule SHAs are on allowed branches\n")
	sb.WriteString("        shell: bash\n")
	sb.WriteString("        run: |\n")
	sb.WriteString("          set -euo pipefail\n")
	sb.WriteString(fmt.Sprintf("          ALLOWED_BRANCHES=(\"%s\" \"%s\")\n\n", git.IntegrationBranch, git.ReleaseBranch))
	sb.WriteString("          paths=$(git config -f .gitmodules --get-regexp path | awk '{print $2}')\n")
	sb.WriteString("          for p in $paths; do\n")
	sb.WriteString("            echo \"== Checking submodule: $p ==\"\n")
	sb.WriteString("            sha=$(git -C \"$p\" rev-parse HEAD)\n")
	sb.WriteString("            echo \"SHA: $sha\"\n\n")
	sb.WriteString("            git -C \"$p\" fetch origin --prune\n\n")
	sb.WriteString("            ok=0\n")
	sb.WriteString("            for b in \"${ALLOWED_BRANCHES[@]}\"; do\n")
	sb.WriteString("              if git -C \"$p\" branch -r --contains \"$sha\" | grep -q \"origin/$b\"; then\n")
	sb.WriteString("                echo \"OK: $sha is contained in origin/$b\"\n")
	sb.WriteString("                ok=1\n")
	sb.WriteString("                break\n")
	sb.WriteString("              fi\n")
	sb.WriteString("            done\n\n")
	sb.WriteString("            if [[ \"$ok\" -ne 1 ]]; then\n")
	sb.WriteString("              echo \"ERROR: $p SHA $sha is NOT on allowed branches: ${ALLOWED_BRANCHES[*]}\"\n")
	sb.WriteString("              exit 2\n")
	sb.WriteString("            fi\n")
	sb.WriteString("          done\n")

	return sb.String()
}

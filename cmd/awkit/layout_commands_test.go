// earlierLayout writes a project as an earlier awkit left it, on a machine
// where links could not be made: the kit and the project's own rules and
// skills under .ai, a copy of both under .claude, a directory for everything
// a run wrote, and a workflow that names the configuration at its earlier
// place.
func earlierLayout(t *testing.T, dir string) {
	t.Helper()
	const config = "version: \"1.2\"\n" +
		"project: {name: demo, type: monorepo}\n" +
		"git: {integration_branch: develop, release_branch: main}\n" +
		"repos:\n  - {name: backend, path: backend/, type: directory, language: go, verify: {build: go build ./..., test: go test ./...}}\n"
	const ignore = "bin/\n\n" +
		"# >>> AI Workflow Kit >>>\n# Runtime state (do not commit)\n.ai/state/\n.ai/results/\n.ai/runs/\n.ai/exe-logs/\n.ai/logs/\n.ai/temp/\n.worktrees/\n" +
		"# Claude Code local settings (do not commit)\n.claude/settings.local.json\n# <<< AI Workflow Kit <<<\n"
	const workflow = "# Generated by awkit from .ai/config/workflow.yaml. Do not edit: awkit keeps this file in step with the config.\n" +
		"# To change it by hand, delete this comment first; awkit then leaves the file alone.\n\nname: ci-backend\n"
	for rel, content := range map[string]string{
		".ai/config/workflow.yaml":                    config,
		".ai/config/workflow.schema.json":             "{}",
		".ai/rules/_kit/git-workflow.md":              "the kit's rule as that version had it",
		".ai/rules/_examples/testing-strategy.md":     "the kit's example",
		".ai/rules/backend.md":                        "the project's rule",
		".ai/skills/principal-workflow/SKILL.md":      "the kit's skill as that version had it",
		".ai/skills/release-notes/SKILL.md":           "the project's skill",
		".claude/rules/_kit/git-workflow.md":          "the kit's rule as that version had it",
		".claude/rules/_examples/testing-strategy.md": "the kit's example",
		".claude/rules/backend.md":                    "the project's rule",
		".claude/skills/principal-workflow/SKILL.md":  "the kit's skill as that version had it",
		".claude/skills/release-notes/SKILL.md":       "the project's skill",
		".claude/agents/pr-reviewer.md":               "the kit's subagent as that version had it",
		".claude/settings.json":                       "{}",
		".github/workflows/ci-backend.yml":            workflow,
		".gitignore":                                  ignore,
		"CLAUDE.md":                                   "Read `.ai/skills/principal-workflow/SKILL.md`\n",
		"AGENTS.md":                                   "Read and obey: `.ai/rules/_kit/git-workflow.md`\n",
		"backend/main.go":                             "package main\n\nfunc main() {}\n",
		"backend/go.mod":                              "module demo\n\ngo 1.25\n",
		// What runs left behind. git ignores it.
		".ai/results/issue-3.json":   "{}",
		".ai/runs/issue-3/plan.md":   "the plan",
		".ai/exe-logs/principal.log": "the log",
		".ai/state/loop_count":       "4",
	} {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func readFile(t *testing.T, dir, rel string) string {
	t.Helper()
	content, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
	if err != nil {
		return "(not there: " + err.Error() + ")"
	}
	return string(content)
}

// `awkit upgrade` moves a project of an earlier awkit to where the files are
// kept now, installs the kit there, and commits all of it: the project is
// left with nothing to tidy up by hand, and with nothing at the earlier
// places.
func TestCmdUpgrade_MovesAProjectOfAnEarlierAwkit(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not available")
	}
	t.Setenv("AWKIT_SKIP_UPDATE_CHECK", "1")
	dir := t.TempDir()
	git := func(args ...string) string {
		t.Helper()
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
		return string(out)
	}
	git("init", "-q", "-b", "develop")
	git("config", "user.email", "test@example.com")
	git("config", "user.name", "Test User")
	git("config", "commit.gpgsign", "false")
	git("config", "core.autocrlf", "false")
	earlierLayout(t, dir)
	git("add", "-A")
	git("commit", "-q", "-m", "the project as an earlier awkit left it")

	out := captureStdout(t, func() {
		if code := cmdUpgrade([]string{dir}); code != 0 {
			t.Errorf("cmdUpgrade() = %d, want 0", code)
		}
	})

	// Committed, all of it.
	if status := strings.TrimSpace(git("status", "--porcelain")); status != "" {
		t.Errorf("the upgrade left changes that are not committed:\n%s", status)
	}
	if subject := strings.TrimSpace(git("log", "-1", "--format=%s")); subject != "[chore] upgrade awkit" {
		t.Errorf("last commit = %q, want the upgrade's", subject)
	}

	tracked := strings.Fields(git("ls-files"))
	sort.Strings(tracked)
	has := func(file string) bool {
		i := sort.SearchStrings(tracked, file)
		return i < len(tracked) && tracked[i] == file
	}
	for _, want := range []string{
		".ai/config.yaml",
		".claude/rules/_kit/git-workflow.md",
		".claude/rules/backend.md",
		".claude/skills/principal-workflow/SKILL.md",
		".claude/skills/principal-workflow/phases/main-loop.md",
		".claude/skills/release-notes/SKILL.md",
		".claude/agents/pr-reviewer.md",
		".claude/agents/conflict-resolver.md",
		".claude/settings.json",
		".github/workflows/ci-backend.yml",
		".gitignore", "CLAUDE.md", "AGENTS.md", "backend/main.go",
	} {
		if !has(want) {
			t.Errorf("%s is not in the project after the upgrade", want)
		}
	}
	for _, file := range tracked {
		for _, earlier := range []string{".ai/config/", ".ai/rules/", ".ai/skills/", ".claude/rules/_examples/"} {
			if strings.HasPrefix(file, earlier) {
				t.Errorf("%s is still in the project", file)
			}
		}
	}

	// The project's own came along unchanged; the kit's is the kit's of now.
	if got := readFile(t, dir, ".ai/config.yaml"); !strings.Contains(got, "project: {name: demo, type: monorepo}") {
		t.Errorf("the configuration did not come along:\n%s", got)
	}
	if got := readFile(t, dir, ".claude/rules/backend.md"); got != "the project's rule" {
		t.Errorf("the project's rule = %q", got)
	}
	if got := readFile(t, dir, ".claude/skills/release-notes/SKILL.md"); got != "the project's skill" {
		t.Errorf("the project's skill = %q", got)
	}
	for _, kit := range []string{".claude/rules/_kit/git-workflow.md", ".claude/skills/principal-workflow/SKILL.md", ".claude/agents/pr-reviewer.md"} {
		if got := readFile(t, dir, kit); strings.Contains(got, "as that version had it") {
			t.Errorf("%s is still the earlier kit's: %q", kit, got)
		}
	}

	// What agents are told names the files where they are.
	for file, want := range map[string]string{
		"CLAUDE.md": ".claude/skills/principal-workflow/SKILL.md",
		"AGENTS.md": ".claude/rules/_kit/git-workflow.md",
	} {
		got := readFile(t, dir, file)
		if !strings.Contains(got, want) || strings.Contains(got, ".ai/skills/") || strings.Contains(got, ".ai/rules/") || strings.Contains(got, ".ai/config/") {
			t.Errorf("%s does not point at the new places (want %s):\n%s", file, want, got)
		}
	}
	// The workflow is still awkit's, and says so in today's words.
	if got := readFile(t, dir, ".github/workflows/ci-backend.yml"); !strings.HasPrefix(got, "# Generated by awkit from .ai/config.yaml. ") || !strings.Contains(got, "go test ./...") {
		t.Errorf("the workflow was not refreshed:\n%s", got)
	}
	// One line of the ignore file covers what a run leaves behind.
	ignore := readFile(t, dir, ".gitignore")
	if !strings.Contains(ignore, "bin/\n") || !strings.Contains(ignore, "\n.ai/state/\n") || strings.Contains(ignore, ".ai/results/") || strings.Contains(ignore, ".ai/exe-logs/") {
		t.Errorf(".gitignore after the upgrade:\n%s", ignore)
	}
	// What runs left behind moved, and stays out of git.
	for rel, want := range map[string]string{
		".ai/state/results/issue-3.json": "{}",
		".ai/state/runs/issue-3/plan.md": "the plan",
		".ai/state/logs/principal.log":   "the log",
		".ai/state/loop_count":           "4",
	} {
		if got := readFile(t, dir, rel); got != want {
			t.Errorf("%s = %q, want %q", rel, got, want)
		}
		if has(rel) {
			t.Errorf("%s is committed", rel)
		}
	}
	for _, gone := range []string{".ai/config", ".ai/rules", ".ai/skills", ".ai/results", ".ai/runs", ".ai/exe-logs"} {
		if _, err := os.Stat(filepath.Join(dir, filepath.FromSlash(gone))); !os.IsNotExist(err) {
			t.Errorf("%s is still there (err %v)", gone, err)
		}
	}

	// The person is told what was moved.
	for _, said := range []string{"Moved to where awkit keeps a project's files now:", ".ai/config/workflow.yaml -> .ai/config.yaml", ".ai/rules -> .claude/rules (the project's rules)"} {
		if !strings.Contains(out, said) {
			t.Errorf("the upgrade does not say %q:\n%s", said, out)
		}
	}

	// A second upgrade has nothing to move and nothing to commit.
	head := strings.TrimSpace(git("rev-parse", "HEAD"))
	again := captureStdout(t, func() {
		if code := cmdUpgrade([]string{dir}); code != 0 {
			t.Errorf("a second cmdUpgrade() = %d, want 0", code)
		}
	})
	if strings.Contains(again, "Moved to where") {
		t.Errorf("a second upgrade moved something:\n%s", again)
	}
	if now := strings.TrimSpace(git("rev-parse", "HEAD")); now != head || strings.TrimSpace(git("status", "--porcelain")) != "" {
		t.Errorf("a second upgrade changed the project: HEAD %s -> %s\n%s", head, now, git("status", "--porcelain"))
	}
}

// A dry run of the upgrade says what would be moved and moves nothing.
func TestCmdUpgrade_DryRunMovesNothing(t *testing.T) {
	t.Setenv("AWKIT_SKIP_UPDATE_CHECK", "1")
	dir := t.TempDir()
	earlierLayout(t, dir)

	out := captureStdout(t, func() {
		if code := cmdUpgrade([]string{"--dry-run", dir}); code != 0 {
			t.Errorf("cmdUpgrade(--dry-run) = %d, want 0", code)
		}
	})

	for _, said := range []string{"Would move the project's files to where awkit keeps them now:", ".ai/config/workflow.yaml -> .ai/config.yaml", "remove .ai/rules/_kit (the kit's)"} {
		if !strings.Contains(out, said) {
			t.Errorf("the dry run does not say %q:\n%s", said, out)
		}
	}
	if got := readFile(t, dir, ".ai/config/workflow.yaml"); !strings.Contains(got, "name: demo") {
		t.Errorf("the dry run moved the configuration: %s", got)
	}
	for _, untouched := range []string{".ai/rules/backend.md", ".ai/skills/principal-workflow/SKILL.md", ".ai/results/issue-3.json", ".claude/rules/_examples/testing-strategy.md"} {
		if strings.HasPrefix(readFile(t, dir, untouched), "(not there") {
			t.Errorf("the dry run removed %s", untouched)
		}
	}
	if _, err := os.Stat(filepath.Join(dir, ".ai", "config.yaml")); !os.IsNotExist(err) {
		t.Errorf("the dry run wrote the configuration at the new place (err %v)", err)
	}
}

// In a project of an earlier awkit, `awkit init` and `awkit uninstall` stop
// and send the person to `awkit upgrade`. Setting the project up again would
// leave it with two of everything, and an uninstall cannot tell the copies
// that version made from the project's own files.
func TestCmdInitAndUninstall_StopInAProjectOfAnEarlierAwkit(t *testing.T) {
	t.Setenv("AWKIT_SKIP_UPDATE_CHECK", "1")
	for name, command := range map[string]func(dir string) int{
		"init":      func(dir string) int { return cmdInit([]string{"--preset", "generic", dir}) },
		"uninstall": func(dir string) int { return cmdUninstall([]string{dir}) },
	} {
		dir := t.TempDir()
		earlierLayout(t, dir)
		code := -1
		var stderr string
		_ = captureStdout(t, func() {
			stderr = captureStderr(func() { code = command(dir) })
		})
		if code != 1 || !strings.Contains(stderr, "awkit upgrade") || !strings.Contains(stderr, "earlier awkit") {
			t.Errorf("awkit %s = %d, want it to stop and name `awkit upgrade`:\n%s", name, code, stderr)
		}
		// Nothing was written, and nothing removed.
		if _, err := os.Stat(filepath.Join(dir, ".ai", "config.yaml")); !os.IsNotExist(err) {
			t.Errorf("awkit %s wrote a configuration (err %v)", name, err)
		}
		for _, untouched := range []string{".ai/config/workflow.yaml", ".ai/rules/backend.md", ".claude/settings.json", ".claude/skills/release-notes/SKILL.md"} {
			if strings.HasPrefix(readFile(t, dir, untouched), "(not there") {
				t.Errorf("awkit %s removed %s", name, untouched)
			}
		}
	}
}

// `awkit uninstall` leaves the project's own files under .claude where they
// are. It used to remove the whole directory.
func TestCmdUninstall_LeavesTheProjectsOwnFiles(t *testing.T) {
	t.Setenv("AWKIT_SKIP_UPDATE_CHECK", "1")
	dir := t.TempDir()
	_ = captureStdout(t, func() {
		if code := cmdInit([]string{"--preset", "generic", dir}); code != 0 {
			t.Fatalf("cmdInit() = %d", code)
		}
	})
	own := map[string]string{
		".claude/rules/backend.md":              "the project's rule",
		".claude/skills/release-notes/SKILL.md": "the project's skill",
		".claude/settings.json":                 "{}",
	}
	for rel, content := range own {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	out := captureStdout(t, func() {
		if code := cmdUninstall([]string{dir}); code != 0 {
			t.Errorf("cmdUninstall() = %d, want 0", code)
		}
	})

	for rel, content := range own {
		if got := readFile(t, dir, rel); got != content {
			t.Errorf("%s = %q after the uninstall", rel, got)
		}
	}
	for _, gone := range []string{".ai", ".claude/rules/_kit", ".claude/skills/principal-workflow", ".claude/agents"} {
		if _, err := os.Stat(filepath.Join(dir, filepath.FromSlash(gone))); !os.IsNotExist(err) {
			t.Errorf("%s is still there after the uninstall (err %v)", gone, err)
		}
	}
	if !strings.Contains(out, ".claude/skills/principal-workflow/SKILL.md") || !strings.Contains(out, "Left in place: CLAUDE.md, AGENTS.md") {
		t.Errorf("the uninstall does not say what it removed and what it left:\n%s", out)
	}
}


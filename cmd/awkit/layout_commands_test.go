// The project may be named as "."; the files are reported by their full path.
func TestProjectWorkflowPaths_TheProjectNamedAsADot(t *testing.T) {
	project := t.TempDir()
	previous, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(project); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(previous) })
	// The project as the command sees it once it has changed into it: on some
	// systems the temporary directory is reached through a link.
	here, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	written := []string{
		filepath.Join(here, ".github", "workflows", "ci-backend.yml"),
		filepath.Join(here, "frontend", ".github", "workflows", "ci.yml"), // a submodule's own
	}
	removed := []string{filepath.Join(here, ".github", "workflows", "ci-old.yml")}
	want := []string{".github/workflows/ci-backend.yml", ".github/workflows/ci-old.yml"}

	for _, target := range []string{".", "./", here} {
		got := projectWorkflowPaths(target, written, removed)
		if len(got) != 2 || got[0] != want[0] || got[1] != want[1] {
			t.Errorf("projectWorkflowPaths(%q) = %v, want %v", target, got, want)
		}
	}
}

// `awkit status` reads from where the files are kept now. In a project that
// has not been upgraded it says so, where it would otherwise read as "nothing
// has run".
func TestCmdStatus_SaysThatAProjectHasNotBeenUpgraded(t *testing.T) {
	// The directories first: the way back out of them is then the first thing
	// undone, before they are removed.
	earlier, current := t.TempDir(), t.TempDir()
	previous, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(previous) })

	earlierLayout(t, earlier)
	if err := os.Chdir(earlier); err != nil {
		t.Fatal(err)
	}
	out := captureStdout(t, func() {
		if code := cmdStatus(nil); code != 0 {
			t.Errorf("cmdStatus() = %d, want 0", code)
		}
	})
	if !strings.Contains(out, "earlier awkit") || !strings.Contains(out, "awkit upgrade") {
		t.Errorf("status in a project of an earlier awkit does not say so:\n%s", out)
	}

	if err := os.MkdirAll(filepath.Join(current, ".ai", "state"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(current, ".ai", "config.yaml"), []byte("project: {name: demo}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(current); err != nil {
		t.Fatal(err)
	}
	out = captureStdout(t, func() {
		if code := cmdStatus(nil); code != 0 {
			t.Errorf("cmdStatus() = %d, want 0", code)
		}
	})
	if strings.Contains(out, "earlier awkit") {
		t.Errorf("status says a project has not been upgraded when it has:\n%s", out)
	}
}
